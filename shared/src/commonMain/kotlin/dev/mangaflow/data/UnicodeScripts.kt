/**
 * Unicode Script property from Unicode 15.0.0, matching the desktop JDK 21 baseline.
 * Source: https://www.unicode.org/Public/15.0.0/ucd/Scripts.txt
 * Copyright © 2022 Unicode, Inc.; license retained in third_party/unicode/LICENSE.txt.
 *
 * This preserves the original per-Char grouping rule: Common/Inherited/Unknown do not
 * establish author-script agreement, and UTF-16 surrogate units remain Unknown.
 * Adjacent BMP ranges of the same script are merged; IDs are local equality keys only.
 */
internal fun unicodeAuthorScript(character: Char): Int? {
    val code = character.code
    var low = 0
    var high = authorScriptRanges.size / 3 - 1
    while (low <= high) {
        val middle = (low + high) ushr 1
        val offset = middle * 3
        when {
            code < authorScriptRanges[offset] -> high = middle - 1
            code > authorScriptRanges[offset + 1] -> low = middle + 1
            else -> return authorScriptRanges[offset + 2]
        }
    }
    return null
}

